// Local Phorge sandbox (Docker) for the phorge provider.
//
// Layout created in the project:
//   <project>/agent-forge/
//     .env                  generated once (ports, random passwords); never overwritten
//     .gitignore            keeps .env / backups / logs out of git
//     project.json          which profile this project uses
//     docker-compose.yml    \
//     Dockerfile             |  copied from the skill's assets/phorge
//     config/ scripts/       |  (refreshed only with --refresh-assets)
//     README.md             /
//     provision.log         docker build / up output

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compose, composeLogged, findFreePort, requireDocker } from '../../docker.js';
import { ForgeError, progress } from '../../output.js';
import { createClient } from './api.js';

const ASSETS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../../assets/phorge');
const TOKEN_PATH = '/var/run/phorge/agent.token';

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

function randomSecret(len = 20) {
  return crypto.randomBytes(len).toString('base64url').slice(0, len);
}

function slug(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 30) || 'project';
}

export function readEnv(dir) {
  const file = path.join(dir, '.env');
  if (!fs.existsSync(file)) return null;
  const env = {};
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) env[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return env;
}

// Returns true when any asset was (re)written, so the caller can record which
// skill version the Docker files came from.
function copyAssets(dir, refresh) {
  let copied = false;
  for (const entry of fs.readdirSync(ASSETS)) {
    const src = path.join(ASSETS, entry);
    const dst = path.join(dir, entry === 'env.example' ? '.env.example' : entry);
    if (fs.existsSync(dst) && !refresh) continue;
    fs.cpSync(src, dst, { recursive: true, force: true });
    copied = true;
  }
  for (const f of fs.readdirSync(path.join(dir, 'scripts'))) {
    if (f.endsWith('.sh')) fs.chmodSync(path.join(dir, 'scripts', f), 0o755);
  }
  return copied;
}

async function writeEnv(dir, root, opts) {
  const port = opts.port ? Number(opts.port) : await findFreePort(8080);
  const tz = opts.timezone || Intl.DateTimeFormat().resolvedOptions().timeZone || 'UTC';
  const hash = crypto.createHash('sha1').update(root).digest('hex').slice(0, 6);
  const env = {
    COMPOSE_PROJECT_NAME: `agent-forge-${slug(path.basename(root))}-${hash}`,
    PHORGE_HOST_PORT: String(port),
    PHORGE_BASE_URI: `http://127.0.0.1:${port}/`,
    PHORGE_ALLOWED_URIS: '',
    PHORGE_TIMEZONE: tz,
    MYSQL_ROOT_PASSWORD: randomSecret(24),
    ADMIN_USERNAME: 'admin',
    ADMIN_EMAIL: 'admin@example.com',
    ADMIN_REALNAME: 'Administrator',
    ADMIN_PASSWORD: randomSecret(16),
    AGENT_USERNAME: opts.agentUsername || 'agent',
    AGENT_EMAIL: 'agent@example.com',
    AGENT_REALNAME: 'Agent',
  };
  const body = [
    '# Generated by agent-forge. Edit, then run: docker compose up -d',
    '# Changing PHORGE_HOST_PORT also requires updating PHORGE_BASE_URI.',
    ...Object.entries(env).map(([k, v]) => `${k}=${v}`),
    '',
  ].join('\n');
  fs.writeFileSync(path.join(dir, '.env'), body, { mode: 0o600 });
  return env;
}

async function waitFor(label, fn, timeoutMs) {
  const deadline = Date.now() + timeoutMs;
  let lastErr;
  while (Date.now() < deadline) {
    try {
      const v = await fn();
      if (v) return v;
    } catch (err) {
      lastErr = err;
    }
    await sleep(3000);
  }
  throw new ForgeError('timeout', `Timed out waiting for ${label}.${lastErr ? ` Last error: ${lastErr.message}` : ''}`, {
    hint: 'Provisioning is idempotent: run the same command again to keep waiting, or check "sandbox logs".',
  });
}

function readToken(dir) {
  const r = compose(dir, ['exec', '-T', 'phorge', 'cat', TOKEN_PATH]);
  const t = r.status === 0 ? r.stdout.trim() : '';
  return /^api-[a-z0-9]+$/i.test(t) ? t : null;
}

// opts: { root, port, timezone, refreshAssets, waitSeconds, agentUsername }
export async function run(opts) {
  requireDocker();
  const root = opts.root;
  const dir = path.join(root, 'agent-forge');
  fs.mkdirSync(dir, { recursive: true });

  const assetsCopied = copyAssets(dir, opts.refreshAssets);
  let env = readEnv(dir);
  const fresh = !env;
  if (fresh) env = await writeEnv(dir, root, opts);
  progress(`${fresh ? 'created' : 'reusing'} ${path.relative(process.cwd(), dir) || dir}/.env (port ${env.PHORGE_HOST_PORT})`);

  const logFile = path.join(dir, 'provision.log');
  const timeoutMs = (Number(opts.waitSeconds) || 900) * 1000;

  progress(`building and starting containers (first run takes a few minutes; log: ${path.relative(process.cwd(), logFile)})`);
  const code = await composeLogged(dir, ['up', '-d', '--build'], logFile);
  if (code !== 0) {
    const tail = fs.readFileSync(logFile, 'utf8').split('\n').slice(-25).join('\n');
    throw new ForgeError('error', `docker compose up failed (exit ${code}).`, { logFile, logTail: tail });
  }

  progress('waiting for Phorge to initialize and mint the agent API token');
  const token = await waitFor('the agent API token', () => readToken(dir), timeoutMs);

  const baseUrl = env.PHORGE_BASE_URI;
  progress(`waiting for the API at ${baseUrl}`);
  const client = createClient({ baseUrl, token });
  const me = await waitFor('the Conduit API', () => client.whoami(), timeoutMs);

  return {
    baseUrl,
    token,
    dir,
    composeProject: env.COMPOSE_PROJECT_NAME,
    agent: me,
    admin: { username: env.ADMIN_USERNAME, password: env.ADMIN_PASSWORD, loginUrl: baseUrl },
    fresh,
    assetsCopied,
  };
}

function ctxDir(ctx) {
  const dir = path.join(ctx.root, 'agent-forge');
  if (!fs.existsSync(path.join(dir, 'docker-compose.yml'))) {
    throw new ForgeError('unconfigured', `No sandbox found at ${dir}. Run "provision" first.`);
  }
  return dir;
}

// Static facts from .env; does not touch Docker.
export function info(ctx) {
  const dir = ctxDir(ctx);
  const env = readEnv(dir) || {};
  return { dir, baseUrl: env.PHORGE_BASE_URI || null, composeProject: env.COMPOSE_PROJECT_NAME || null };
}

export function status(ctx) {
  const dir = ctxDir(ctx);
  const env = readEnv(dir) || {};
  const r = compose(dir, ['ps', '--all', '--format', 'json']);
  let services = [];
  if (r.status === 0) {
    services = r.stdout
      .trim()
      .split('\n')
      .filter(Boolean)
      .flatMap((l) => {
        try {
          const j = JSON.parse(l);
          return Array.isArray(j) ? j : [j];
        } catch {
          return [];
        }
      })
      .map((s) => ({ service: s.Service, state: s.State, status: s.Status }));
  }
  const running = services.length > 0 && services.every((s) => s.state === 'running');
  return { dir, baseUrl: env.PHORGE_BASE_URI, composeProject: env.COMPOSE_PROJECT_NAME, running, services };
}

export function start(ctx) {
  const dir = ctxDir(ctx);
  const r = compose(dir, ['up', '-d'], { timeout: 600000 });
  if (r.status !== 0) throw new ForgeError('error', 'docker compose up failed.', { stderr: r.stderr.slice(-2000) });
  return status(ctx);
}

export function stop(ctx) {
  const dir = ctxDir(ctx);
  const r = compose(dir, ['stop'], { timeout: 120000 });
  if (r.status !== 0) throw new ForgeError('error', 'docker compose stop failed.', { stderr: r.stderr.slice(-2000) });
  return status(ctx);
}

export function logs(ctx, { tail = 100 } = {}) {
  const dir = ctxDir(ctx);
  const r = compose(dir, ['logs', '--no-color', '--tail', String(tail)]);
  return { dir, logs: (r.stdout + r.stderr).split('\n') };
}

// Removes containers AND volumes (all tracker data). Files in agent-forge/ stay.
export function destroy(ctx) {
  const dir = ctxDir(ctx);
  const r = compose(dir, ['down', '--volumes', '--remove-orphans'], { timeout: 180000 });
  if (r.status !== 0) throw new ForgeError('error', 'docker compose down failed.', { stderr: r.stderr.slice(-2000) });
  return { dir, destroyed: true, note: 'Containers and volumes removed. Run "provision" to create a fresh instance.' };
}
